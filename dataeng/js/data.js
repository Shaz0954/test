export const GLOSSARY = [
  ['ACID', 'Atomicity, Consistency, Isolation, Durability — the guarantees of a transactional database.'],
  ['Airflow', 'Open-source orchestrator where pipelines are Python-defined DAGs of tasks.'],
  ['Avro', 'Row-oriented binary format with an embedded schema; popular for Kafka messages because it supports schema evolution.'],
  ['Backfill', 'Re-running a pipeline for historical dates, e.g. after a bug fix or when a new table is introduced.'],
  ['Batch processing', 'Processing bounded chunks of data on a schedule (hourly, daily), as opposed to continuously.'],
  ['CDC', 'Change Data Capture — streaming inserts, updates and deletes out of a database, usually by reading its transaction log.'],
  ['Columnar storage', 'Storing values column-by-column so analytical queries read only the columns they need and compress well.'],
  ['Compaction', 'Merging many small files (or log segments) into fewer larger ones to keep reads fast.'],
  ['Consumer group', 'A set of Kafka consumers sharing work: each partition is read by exactly one member of the group.'],
  ['Consumer lag', 'How far a consumer is behind the newest message in a partition (log end offset − committed offset).'],
  ['CTE', 'Common Table Expression — a named sub-query introduced with WITH that makes SQL readable and composable.'],
  ['DAG', 'Directed Acyclic Graph — tasks plus dependencies with no cycles; the shape of every pipeline.'],
  ['Data contract', 'An explicit, versioned agreement between a data producer and its consumers about schema, semantics and SLAs.'],
  ['Data lake', 'Cheap object storage (S3, GCS, ADLS) holding raw files in open formats.'],
  ['Data lineage', 'The graph of which datasets and columns feed which others; essential for impact analysis and debugging.'],
  ['Data mart', 'A curated, business-facing subset of the warehouse built for a specific team or use case.'],
  ['Data warehouse', 'A database optimised for analytics over large, structured, historical data (Snowflake, BigQuery, Redshift).'],
  ['dbt', 'Tool that turns SELECT statements into tested, documented, dependency-ordered tables and views.'],
  ['Dead-letter queue', 'Where a pipeline parks records it could not process so the rest of the stream keeps flowing.'],
  ['Dimension', 'Descriptive context for facts — who, what, where, when (customer, product, date).'],
  ['ELT', 'Extract, Load, Transform — load raw data into the warehouse first, transform there with SQL.'],
  ['ETL', 'Extract, Transform, Load — transform data before loading it into the target system.'],
  ['Exactly-once', 'A processing guarantee where each record affects the result exactly one time, even after failures.'],
  ['Fact table', 'A table of measurable events (sales, clicks) at a declared grain, with foreign keys to dimensions.'],
  ['Grain', 'What one row of a table represents, e.g. “one row per order line”. Declare it before anything else.'],
  ['Idempotent', 'Safe to run more than once: re-running produces the same end state with no duplicates.'],
  ['Iceberg', 'Open table format that adds ACID transactions, schema evolution and time travel to files in a data lake.'],
  ['Incremental load', 'Processing only new or changed data since the last run instead of everything.'],
  ['Kafka', 'Distributed, durable, partitioned commit log used as the backbone for event streaming.'],
  ['Lakehouse', 'Architecture combining lake storage with warehouse features via table formats like Iceberg or Delta Lake.'],
  ['Medallion architecture', 'Layering data as bronze (raw), silver (cleaned) and gold (business-ready).'],
  ['OLAP', 'Online Analytical Processing — few, large, read-heavy queries over lots of rows.'],
  ['OLTP', 'Online Transaction Processing — many small, fast reads and writes (the app database).'],
  ['Offset', 'The position of a message within a Kafka partition.'],
  ['Parquet', 'The dominant columnar file format: compressed, splittable, with per-column statistics for skipping data.'],
  ['Partition pruning', 'Skipping whole partitions (e.g. dates) that a query’s filter rules out.'],
  ['Partitioning', 'Splitting a dataset by a key (date, region) so engines can read or process pieces independently.'],
  ['PII', 'Personally Identifiable Information — data that can identify a person and must be protected.'],
  ['Schema evolution', 'Changing a schema over time (adding columns, widening types) without breaking readers.'],
  ['Schema-on-read', 'Storing raw data and applying structure only when it is queried.'],
  ['SCD', 'Slowly Changing Dimension — techniques for handling dimension attributes that change over time.'],
  ['Shuffle', 'Redistributing rows across the cluster by key (for joins/group-bys); the most expensive Spark operation.'],
  ['Skew', 'When a few keys hold most of the data, so a few partitions do most of the work.'],
  ['SLA / SLO', 'The promised (SLA) or targeted (SLO) level of service, e.g. “orders table fresh by 07:00, 99.5% of days”.'],
  ['Spark', 'Distributed compute engine for large-scale batch and streaming transformations.'],
  ['Star schema', 'A central fact table joined to surrounding dimension tables.'],
  ['Surrogate key', 'A warehouse-generated key (not from the source) identifying a dimension row or version.'],
  ['Upsert / MERGE', 'Insert new rows and update existing ones in one statement, keyed on a unique identifier.'],
  ['Watermark', 'A stream processor’s estimate of event-time progress; decides when a window is complete.'],
  ['Window function', 'A SQL function computed across related rows (OVER …) without collapsing them.'],
].map(([term, def]) => ({ term, def }));
